// ---------- 再生制御 ----------
const Voice = {
  worker: null, pending: new Map(), reqId: 0, cache: new Map(), cur: null, gen: 0,

  init() {
    if (this.inited) return; this.inited = true;
    try {
      if (typeof Worker !== 'undefined' && location.protocol !== 'file:') {
        this.worker = new Worker('koe.js');
        this.worker.onmessage = e => { const f = this.pending.get(e.data.id); if (f) { this.pending.delete(e.data.id); f(e.data.pcm); } };
        this.worker.onerror = () => { this.worker = null; this.pending.forEach(f => f(null)); this.pending.clear(); };
      }
    } catch (e) { this.worker = null; }
  },
  vol() { const d = (typeof SaveSys !== 'undefined') && SaveSys.data; return d && d.voiceVol !== undefined ? d.voiceVol : 0.9; },
  opts(v) {
    const c = typeof v === 'string' ? (KOE_CAST[v] || KOE_CAST.mq_narr) : (v || KOE_CAST.mq_narr);
    return { f0: c.f0, fs: c.fs, ins: c.ins, breath: c.br, speed: c.sp || 1, particle: false, devoice: true, longv: true };
  },
  num(n) { // 整数 → かな (0〜99999)
    const d = ['', 'いち', 'に', 'さん', 'よん', 'ご', 'ろく', 'なな', 'はち', 'きゅう'];
    if (n === 0) return 'ぜろ';
    let s = '';
    const man = Math.floor(n / 10000); if (man) { s += d[man] + 'まん'; n %= 10000; }
    const sen = Math.floor(n / 1000); if (sen) { s += sen === 1 ? 'せん' : sen === 3 ? 'さんぜん' : sen === 8 ? 'はっせん' : d[sen] + 'せん'; n %= 1000; }
    const hyaku = Math.floor(n / 100); if (hyaku) { s += hyaku === 1 ? 'ひゃく' : hyaku === 3 ? 'さんびゃく' : hyaku === 6 ? 'ろっぴゃく' : hyaku === 8 ? 'はっぴゃく' : d[hyaku] + 'ひゃく'; n %= 100; }
    const ju = Math.floor(n / 10); if (ju) { s += (ju === 1 ? '' : d[ju]) + 'じゅう'; n %= 10; }
    return s + d[n];
  },
  // 1行の読みを決める (登録済み → そのまま / 未登録 → 記号を落として数字をかなに)
  lineYomi(line) {
    const e = KOE_YOMI[line];
    if (e === undefined) return { y: line.replace(/\d+/g, m => this.num(+m)).replace(/[「」『』【】…・─]/g, ' '), v: null };
    return Array.isArray(e) ? { y: e[0], v: e[1] } : { y: e, v: null };
  },
  segments(text) {
    const segs = [];
    for (const line of String(text).split('\n')) {
      if (!line.trim()) continue;
      const s = this.lineYomi(line);
      const last = segs[segs.length - 1];
      if (last && last.v === s.v) last.y += ' ' + s.y; else segs.push(s);
    }
    return segs;
  },
  yomiStr(text) { return this.segments(text).map(s => s.y).join(' '); },
  // 漢字が残っていないか(検証用)
  unresolved(text) { return this.segments(text).filter(s => /[一-鿿]/.test(s.y)).map(s => s.y); },

  render(y, voice) {
    const o = this.opts(voice), key = y + '|' + o.f0 + '|' + o.fs + '|' + o.ins + '|' + o.breath + '|' + o.speed;
    if (this.cache.has(key)) return Promise.resolve(this.cache.get(key));
    const done = pcm => { this.cache.set(key, pcm); if (this.cache.size > 80) this.cache.delete(this.cache.keys().next().value); return pcm; };
    if (this.worker) {
      const id = ++this.reqId;
      return new Promise(res => { this.pending.set(id, pcm => res(done(pcm))); this.worker.postMessage({ id, text: y, o }); });
    }
    let pcm = null; try { const r = KOE.render(y, o); pcm = r ? r.pcm : null; } catch (e) {}
    return Promise.resolve(done(pcm));
  },
  prefetch(text, voice) { if (this.vol() <= 0) return; for (const s of this.segments(text)) this.render(s.y, s.v || voice); },

  playP(pcm, radio, vol) {
    return new Promise(res => {
      if (typeof audioCtx === 'undefined' || !audioCtx) { res(); return; }
      const buf = audioCtx.createBuffer(1, pcm.length, KOE.SR); buf.getChannelData(0).set(pcm);
      const src = audioCtx.createBufferSource(), g = audioCtx.createGain();
      src.buffer = buf; g.gain.value = vol;
      let node = src;
      if (radio) { // 無線っぽい音質
        const bp = audioCtx.createBiquadFilter(); bp.type = 'bandpass'; bp.frequency.value = 1600; bp.Q.value = 0.9;
        src.connect(bp); node = bp; g.gain.value = vol * 1.6;
      }
      node.connect(g); g.connect(audioCtx.destination);
      src.onended = () => res();
      src.start(audioCtx.currentTime + 0.02);
      this.cur = { src };
    });
  },
  // 会話の読み上げ(前の会話は止める)。o: { yomi:明示の読み, radio:無線風 }
  async talk(text, voice, o) {
    o = o || {};
    this.stop();
    const vol = this.vol(); if (vol <= 0 || typeof KOE === 'undefined') return;
    const gen = this.gen;
    const segs = o.yomi ? [{ y: o.yomi, v: null }] : this.segments(text);
    if (!segs.length) return;
    segs.forEach(s => this.render(s.y, s.v || voice)); // 先に全部計算を始める
    this.duck(true);
    for (const s of segs) {
      const pcm = await this.render(s.y, s.v || voice);
      if (gen !== this.gen) return;
      if (pcm && pcm.length) await this.playP(pcm, o.radio, vol);
      if (gen !== this.gen) return;
    }
    this.cur = null; this.duck(false);
  },
  stop() {
    this.gen++;
    if (this.cur) { try { this.cur.src.onended = null; this.cur.src.stop(); } catch (e) {} this.cur = null; }
    this.duck(false);
  },
  // かけ声(会話とは別に重ねて鳴らす。読みを直接渡す)
  async shout(y, voice, vol) {
    const v = this.vol(); if (v <= 0 || typeof KOE === 'undefined') return;
    const pcm = await this.render(y, voice);
    if (!pcm || !pcm.length || typeof audioCtx === 'undefined' || !audioCtx) return;
    const buf = audioCtx.createBuffer(1, pcm.length, KOE.SR); buf.getChannelData(0).set(pcm);
    const src = audioCtx.createBufferSource(), g = audioCtx.createGain();
    src.buffer = buf; g.gain.value = v * (vol === undefined ? 1 : vol);
    src.connect(g); g.connect(audioCtx.destination); src.start(audioCtx.currentTime + 0.02);
  },
  duck(on) { if (typeof BGM !== 'undefined') BGM.duck = on ? 0.35 : 1; }
};
